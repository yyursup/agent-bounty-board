// Copies the BountyBoard ABI and creation bytecode from the Foundry build into typed modules.
// The bytecode feeds the /deploy page; it must come from the same build settings BscScan verifies.
// Run `forge build` in /contracts first, then `npm run sync-abi`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = resolve(here, "../../contracts/out/BountyBoard.sol/BountyBoard.json");
const target = resolve(here, "../src/lib/contracts/abi/bountyBoard.ts");
const bytecodeTarget = resolve(here, "../src/lib/contracts/abi/bountyBoardBytecode.ts");

const { abi, bytecode } = JSON.parse(readFileSync(artifact, "utf8"));
const banner = "// Generated by scripts/sync-abi.mjs from contracts/out. Do not edit by hand.\n";
writeFileSync(
  target,
  `${banner}export const bountyBoardAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`Wrote ${abi.length} ABI entries to ${target}`);
writeFileSync(
  bytecodeTarget,
  `${banner}export const bountyBoardBytecode = "${bytecode.object}" as const;\n`,
);
console.log(
  `Wrote ${(bytecode.object.length - 2) / 2} bytes of creation code to ${bytecodeTarget}`,
);
